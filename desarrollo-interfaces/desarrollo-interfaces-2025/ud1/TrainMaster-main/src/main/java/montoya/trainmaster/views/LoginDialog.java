    //Metodo que desencadena un evento al pulsar el 'button Login' del JDialog, verifica si el usuario esta en la base de datos.
    private void jButtonLoginActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonLoginActionPerformed

        loggedInEmail = jTextFieldEmail.getText();
        Usuari usuari= Usuari.getUsuariLogIn(loggedInEmail);  //Obtener usuario de la DB 
        
        //Verificamos que el usuario es instructor.
        if(usuari.isInstructor()){
            //Comprobar contraseña
            char [] passwordVerify = jPasswordField.getPassword();   //Contraseña ingresada es almacenada en 'passwordVerify'
            String userPasswordHashInDB = usuari.getPasswordHash(); //obtención del HASH y guardado en 'userPasswordHashInDB'
            var result = BCrypt.verifyer().verify(passwordVerify, userPasswordHashInDB);    //Comparación de contraseña introducida con HASH
            
            if(result.verified){
                JFrameMain.setLoggedInstructor(usuari);
                JOptionPane.showMessageDialog(this, "Login successful. Welcome " + usuari.getNom() + "!");
                JFrameMain.showUserPanel();  // Llamar al método para mostrar JPanelUsers en el frame principal
                JFrameMain.enableButtonsMenuEdit();
                dispose();
            }else {
                jLabelMessage.setText("Error: invalid password");
            }
            
        }else {
            jLabelMessage.setText("Error: user not found");   
        }
    }//GEN-LAST:event_jButtonLoginActionPerformed

