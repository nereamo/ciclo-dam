    //Llamar al método para que al seleccionar un usuario del jComboBox, se muestren los workouts asiggnades a este
    private void jComboBoxUserActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jComboBoxUserActionPerformed
       int selectedIndex = jComboBoxUser.getSelectedIndex();
    
        // Verificar que el índice seleccionado sea válido
        if (selectedIndex >= 0 && selectedIndex < userList.size()) {
            Usuari selectedUser = userList.get(selectedIndex);
        
            // Llama al método para cargar los entrenamientos del usuario seleccionado en la tabla
            mostrarWorkoutsUsuarioTable(selectedUser.getId());
        
        }   
    }//GEN-LAST:event_jComboBoxUserActionPerformed

    //Al hacer 'click' en un workout de la tabla, muestra los ejercicios integrados
    private void jTableWorkoutsUserMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_jTableWorkoutsUserMouseClicked
        int selectedRow = jTableWorkoutsUser.getSelectedRow();
    
        // Verifica que haya una fila seleccionada
        if (selectedRow != -1) {
            
            int workoutId = workoutIdList.get(selectedRow); //Obtiene el ID del workout seleccionado en la primera columna de la fila

            
            mostrarEjercicios(workoutId);   //Llama al método para mostrar los ejercicios del workout seleccionado
        }
    }//GEN-LAST:event_jTableWorkoutsUserMouseClicked

    

