    //Método que carga los usuarios del instructor en el JComboBox
    private void loadUsersInComboBox() {
        // Obtener los usuarios asignados al instructor
        userList = Usuari.userInstructor();
        
        // Crear un modelo para el JComboBox
        DefaultComboBoxModel<String> comboBoxModel = new DefaultComboBoxModel<>();
        
        // Llenar el ComboBox con los nombres de los usuarios
        for (Usuari user : userList) {
            comboBoxModel.addElement(user.getNom());  // Usar el nombre del usuario
        }
        
         jComboBoxUser.setModel(comboBoxModel);
       
        // Asegurarse de que el ComboBox se actualice visualmente
        jComboBoxUser.revalidate();
        jComboBoxUser.repaint();
        }
    
    //Método para cargar los entrenamientos del usuario en la tabla al seleccionar un usuario del JComboBox
    private void mostrarWorkoutsUsuarioTable(int userId) {
        try{
            ArrayList<Workouts> workouts = Workouts.getWorkoutsUser(userId);    //Array de los usuarios

            // Crear un modelo para la lista
            DefaultTableModel model= (DefaultTableModel) jTableWorkoutsUser.getModel();
            model.setRowCount(0);
            
            for (Workouts workout : workouts) { //Datos de las columnas de la tabla
                workoutIdList.add(workout.getId());
                model.addRow(new Object[]{
                   //workout.getId(),
                   workout.getForDate(),
                  // workout.getUserId(),
                   workout.getComments()
                });
            }
        
        }catch(Exception e){
            e.printStackTrace();
        }  
    }
    
    //Método para mostrar los ejercicios de un workout en el jListExercises
    private void mostrarEjercicios(int workoutId) {
        
        ArrayList<Exercicis> exercises = Exercicis.getExercisesInWorkout(workoutId);    //Obtiene la lista de ejercicios asociados al workoutId

        
        DefaultListModel<String> listModel = new DefaultListModel<>();  //Modelo de lista para actualizar el jListExercises
    
        if (exercises.isEmpty()) {
        listModel.addElement("No exercises available");
    } else {
        for (Exercicis exercise : exercises) {
            listModel.addElement(exercise.getNomExercici() + " - " + exercise.getDescripcio());
        }
    }
    jListExercises.setModel(listModel);
}
    
