     //Cargamos todos los ejercicios de la BD al ComboBox
    private void cargarExercisesComboBox() {
        exerciseList = Exercicis.getAllExercises(); // Obtiene la lista de ejercicios de la base de datos
        DefaultComboBoxModel<String> exerciseModel = new DefaultComboBoxModel<>();
 
        for (Exercicis e : exerciseList) {
            exerciseModel.addElement(e.toString()); // Añadir cada ejercicio al ComboBox
        }
        
        jComboBoxExercises.setModel(exerciseModel);   // Asignar el modelo al JComboBox  
    }
    
    //Cargamos todos los workouts de la BD al ComboBox
    private void cargarWorkoutsComboBox() {
        workoutsList = Workouts.getAllWorkouts(); // Obtiene la lista de workouts de la base de datos
        DefaultComboBoxModel<String> workoutModel = new DefaultComboBoxModel<>();
 
        for (Workouts w : workoutsList) {
            workoutModel.addElement(w.getComments()); //Mostrar comentarios y fecha en el JComboBox
        }
        
        jComboBoxWorkout.setModel(workoutModel);   //Asignar el modelo al JComboBox  
    }
    
    // Método estático save() para guardar los ejercicios al workout en la base de datos
    public static void saveExerciseInWorkout(int workoutId, int exerciseId) throws SQLException {
        String query = "INSERT INTO ExercicisWorkouts (IdWorkout, IdExercici) VALUES (?, ?)";

        try (Connection conn = DataAccess.getConnection(); PreparedStatement stmt = conn.prepareStatement(query)) {

            // Asignar valores a la declaración preparada
            stmt.setInt(1, workoutId);  // Asigna el workoutId
            stmt.setInt(2, exerciseId);  // Asigna el exerciseId

            // Ejecutar la consulta de inserción
            stmt.executeUpdate();

        } catch (SQLException ex) {
            Logger.getLogger(Workouts.class.getName()).log(Level.SEVERE, "Error al guardar el ejercicio en el workout", ex);
            throw ex;
        }
    }
    

