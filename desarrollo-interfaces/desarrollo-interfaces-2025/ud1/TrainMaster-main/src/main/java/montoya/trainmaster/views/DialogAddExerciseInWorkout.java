    //Tras todas las verificaciones, si todo es correcto, al pulsar el boton Add, se añadiran los ejercicios al workout
    private void jButtonAddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonAddActionPerformed
        try {
            // Obtener el workout y el ejercicio seleccionados
            Workouts selectedWorkout = workoutsList.get(jComboBoxWorkout.getSelectedIndex());
            Exercicis selectedExercici = exerciseList.get(jComboBoxExercises.getSelectedIndex());

            // Validar que los elementos seleccionados no sean nulos
            if (selectedWorkout == null || selectedExercici == null) {
                JOptionPane.showMessageDialog(this, "Por favor, seleccione un Workout y un Ejercicio.", "Error", JOptionPane.ERROR_MESSAGE);
                return; // Salir del método si no se seleccionó un ejercicio o workout
            }

            // Llamar al método para insertar el ejercicio en el workout en la base de datos
            saveExerciseInWorkout(selectedWorkoutId, selectedExerciseId);

            // Mostrar un mensaje de éxito
            JOptionPane.showMessageDialog(this, "Ejercicio añadido al workout correctamente.", "Éxito", JOptionPane.INFORMATION_MESSAGE);

            // Opcionalmente, puedes actualizar cualquier componente o cerrar el formulario
            dispose();

        } catch (SQLException e) {
            // Mostrar mensaje de error en caso de una SQLException
            JOptionPane.showMessageDialog(this, "Error al añadir el ejercicio al workout: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
            e.printStackTrace();
        } catch (Exception e) {
            // Mostrar mensaje de error para cualquier otra excepción
            JOptionPane.showMessageDialog(this, "Error inesperado: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
            e.printStackTrace();
        }
    }//GEN-LAST:event_jButtonAddActionPerformed

    //jComboBox workouts para poder seleccionar un workout y obtener su Id
    private void jComboBoxWorkoutActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jComboBoxWorkoutActionPerformed
        // Obtener el índice del usuario seleccionado en el JComboBox
        int selectedIndex = jComboBoxWorkout.getSelectedIndex();
    
        // Verificar que el índice seleccionado sea válido
        if (selectedIndex >= 0 && selectedIndex < workoutsList.size()) {
        
            Workouts selectedWorkout = workoutsList.get(selectedIndex);// Obtener el usuario seleccionado desde la lista de usuarios
        
            selectedWorkoutId=selectedWorkout.getId();  //Almacena el Id del workout
        }
    }//GEN-LAST:event_jComboBoxWorkoutActionPerformed

