    //Una veze seleccionado usuario, fecha y commentario del workout, se creara en la BD
    private void createButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_createButtonActionPerformed

        String comment = jTextComment.getText().trim();

        if (comment.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Debe ingresar un comentario.", "Error", JOptionPane.ERROR_MESSAGE);
        } else {
            try {
                // Obtener la fecha seleccionada en el JSpinner y formatearla como String
                Date dateWork = (Date) jSpinnerForDate.getValue();
                SimpleDateFormat dateFormat = new SimpleDateFormat("yyyy-MM-dd HH:mm:ss");
                String fechaFormateada = dateFormat.format(dateWork);

                saveWorkoutBD(selectedUserId, comment, fechaFormateada);  // Guardar en la base de datos
                JOptionPane.showMessageDialog(this, "Workout guardado exitosamente.", "Éxito", JOptionPane.INFORMATION_MESSAGE);
                dispose();
            } catch (NumberFormatException e) {
                JOptionPane.showMessageDialog(this, "ID de usuario inválido.", "Error", JOptionPane.ERROR_MESSAGE);
            } catch (SQLException ex) {
                JOptionPane.showMessageDialog(this, "Error al guardar el workout en la base de datos.", "Error", JOptionPane.ERROR_MESSAGE);
            }
        }
    }//GEN-LAST:event_createButtonActionPerformed

    //Accion que al seleccionar un usuario del jComboBox 
    private void jComboUserActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jComboUserActionPerformed

        // Obtener el índice del usuario seleccionado en el JComboBox
        int selectedIndex = jComboUser.getSelectedIndex();

        // Verificar que el índice seleccionado sea válido
        if (selectedIndex >= 0 && selectedIndex < userList.size()) {

            Usuari selectedUser = userList.get(selectedIndex);  //Obtener el usuario seleccionado desde la lista de usuarios

            selectedUserId = selectedUser.getId();  //almacena el Id del usuario seleccionado 
        }
    }//GEN-LAST:event_jComboUserActionPerformed


