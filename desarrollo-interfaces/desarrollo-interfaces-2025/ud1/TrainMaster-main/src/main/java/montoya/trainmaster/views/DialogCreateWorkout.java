    //Método que carga todos los usuarios pertenecientes al instructor en el jComboBox 
    private void allUsers() {

        userList = Usuari.userInstructor(); //Lista de los usuarios del instructor
        DefaultComboBoxModel<String> dcbm = new DefaultComboBoxModel<>();

        for (Usuari u : userList) {
            dcbm.addElement(u.getNom()); //Texto que se mostrará en el JComboBox
        }

        jComboUser.setModel(dcbm);   //Modelo del JComboBox  
    }

    //Método estático save() para guardar el workout en la base de datos
    public static void saveWorkoutBD(int userId, String comments, String forDate) throws SQLException {

        String query = "INSERT INTO Workouts (ForDate, UserId, Comments) VALUES (?, ?, ?)";

        try (Connection conn = DataAccess.getConnection(); PreparedStatement stmt = conn.prepareStatement(query)) {

            // Asignar valores a la declaración preparada
            stmt.setString(1, forDate);  // Asigna ForDate como String en formato "yyyy-MM-dd HH:mm:ss"
            stmt.setInt(2, userId);  // Asigna UserId
            stmt.setString(3, comments);  // Asigna Comments
            stmt.executeUpdate();

        } catch (SQLException ex) {
            Logger.getLogger(Workouts.class.getName()).log(Level.SEVERE, "Error al guardar el workout", ex);
            throw ex;
        }
    }

