public class Bloc01Ejer04 {

    public static void main(String[] args) {
        
        //El tipo 'byte' ocupa menor espacio
        final byte valorMinimo = 34;  
        
        //El tipo 'String' es para cadena de carácteres
        String dia = "Martes";    
        
        //El tipo 'char' sirve para una letra
        char letra = 'o'; 
        
        //El tipo 'double' sirve para decimales
        double salario = 1.500 ;

        //El tipo 'int' sirve para numero enteros entre -2.147.483.648 hasta 2.147.483.647        
        int influencer = 300014;       
        
        System.out.println(valorMinimo);
        System.out.println(dia);
        System.out.println(letra);
        System.out.println(salario);
        System.out.println(influencer);
    }
}
